/* 16x16 pixel icons. "#" = solid, "+" = half-tone, "." = empty.
   mirror: rows are the left 8 columns and get mirrored. from + transform: derive from another icon.
   grid(fn) computes rows from (x, y) for shapes that are easier as maths (diagonals, curves). */
const grid = (fn) =>
  Array.from({ length: 16 }, (_, y) => Array.from({ length: 16 }, (_, x) => fn(x, y)).join(''));

/* Magnifier with a 1px plus or minus, centred on pixel (6, 6). */
const lens = (plus) =>
  grid((x, y) => {
    const d = Math.hypot(x - 6, y - 6);
    if (d >= 4.6 && d <= 6.2) return '#';
    if (x >= 10 && y >= 10 && x <= 14 && y <= 14 && Math.abs(x - y) <= 1) return '#';
    if (y === 6 && Math.abs(x - 6) <= 2) return '#';
    return plus && x === 6 && Math.abs(y - 6) <= 2 ? '#' : '.';
  });

