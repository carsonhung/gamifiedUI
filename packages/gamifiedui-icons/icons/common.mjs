/* 16x16 pixel icons. "#" = solid, "+" = half-tone, "." = empty.
   mirror: rows are the left 8 columns and get mirrored. from + transform: derive from another icon.
   grid(fn) computes rows from (x, y) for shapes that are easier as maths (diagonals, curves). */
const grid = (fn) =>
  Array.from({ length: 16 }, (_, y) => Array.from({ length: 16 }, (_, x) => fn(x, y)).join(''));

/* Christmas tree whose ornaments are holes; animated.mjs lights alternate sets of them. */
const XMAS = [
  '.......##.......', '......####......', '.......##.......', '......####......',
  '.....######.....', '......####......', '.....######.....', '....########....',
  '.....######.....', '....########....', '...##########...', '..############..',
  '......####......', '......####......', '................', '................',
];
export const ORNAMENTS = [[8, 3], [6, 4], [9, 6], [5, 7], [10, 7], [7, 9], [4, 10], [11, 10], [8, 11], [3, 11]];
export const christmasTree = (holes, lit = []) =>
  XMAS.map((row, y) =>
    [...row]
      .map((c, x) => {
        if (lit.some(([hx, hy]) => hx === x && hy === y)) return '+';
        return holes.some(([hx, hy]) => hx === x && hy === y) ? '.' : c;
      })
      .join(''),
  );

/* Ribboned medal with a 3x5 place number cut into it. */
const DIGITS = {
  1: ['.#.', '##.', '.#.', '.#.', '###'],
  2: ['##.', '..#', '.#.', '#..', '###'],
  3: ['##.', '..#', '.#.', '..#', '##.'],
};
const medal = (place) =>
  grid((x, y) => {
    if (y <= 3 && ((x - y >= 1 && x - y <= 3) || (14 - x - y >= 1 && 14 - x - y <= 3))) return '#';
    if (y === 4) return x >= 5 && x <= 9 ? '#' : '.';
    const d = Math.hypot(x - 7, y - 9.5);
    if (d > 5.1 || (d >= 3.7 && d <= 4.3)) return '.';
    return DIGITS[place][y - 7]?.[x - 6] === '#' ? '.' : '#';
  });

/* Three rows of waves; animated.mjs rolls them by shifting the phase. */
export const waves = (shift) =>
  grid((x, y) => {
    const band = [3, 7, 11].findIndex((top) => y === top || y === top + 1);
    if (band === -1) return '.';
    const phase = (((x + shift + (band === 1 ? 4 : 0)) % 8) + 8) % 8;
    return (y % 4 === 3 ? '.###....' : '#...####')[phase];
  });

/* A size x size letter Z, for the sleep icon. */
const zed = (size) =>
  Array.from({ length: size }, (_, r) =>
    r === 0 || r === size - 1 ? '#'.repeat(size) : '.'.repeat(size - 1 - r) + '#' + '.'.repeat(r),
  );

/* Head-and-shoulders bust. `hat` overlays rows (index -> 16-char string, "." = transparent),
   `hair` adds half-tone locks beside the face, `glasses` cuts two lenses. */
const person = ({ hat = {}, hair = false, glasses = false } = {}) =>
  grid((x, y) => {
    const overlay = hat[y]?.[x];
    if (overlay === 'o') return '.';
    if (overlay && overlay !== '.') return overlay;
    if (glasses && y === 6 && (x === 5 || x === 6 || x === 9 || x === 10)) return '.';
    if (Math.hypot(x - 7.5, y - 6.5) <= 2.9) return '#';
    if (y >= 11 && ((x - 7.5) / 6.2) ** 2 + ((y - 15.5) / 4.6) ** 2 <= 1) return '#';
    return hair && y >= 4 && y <= 11 && (x === 3 || x === 4 || x === 11 || x === 12) ? '+' : '.';
  });

