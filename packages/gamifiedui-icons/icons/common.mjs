/* Page with a folded corner and a solid label band; the three-letter `label` is cut out of the band. */
const fileType = (label) =>
  grid((x, y) => {
    if (y >= 7 && y <= 13 && x >= 1 && x <= 14) {
      const col = x - 3;
      const glyph = GLYPHS[label[Math.floor(col / 4)]];
      const on = col >= 0 && col < 11 && col % 4 < 3 && y >= 8 && y <= 12 && glyph?.[y - 8][col % 4] === '#';
      return on ? '.' : '#';
    }
    if (x < 3 || x > 12 || y < 1 || y > 14 || x - y > 9) return '.';
    if (x - y === 9 || (x === 10 && y <= 3) || (y === 3 && x >= 10)) return '#';
    return x === 3 || x === 12 || y === 1 || y === 14 ? '#' : '.';
  });

/* A 16x11 flag on rows 2-12, centred on (7.5, 7). */
const flag = (paint) => grid((x, y) => (y < 2 || y > 12 ? '.' : paint(x, y)));
const frame = (x, y) => x === 0 || x === 15 || y === 2 || y === 12;
const BAUHINIA = ['...##...', '#..##..#', '##.##.##', '.######.', '..####..', '.######.', '.##..##.', '##....##'];

const star = (x, y, cx, cy, r) => {
  const a = (Math.atan2(y - cy, x - cx) + Math.PI / 2 + Math.PI * 4) % ((Math.PI * 2) / 5);
  return Math.hypot(x - cx, y - cy) <= r * (0.45 + 0.55 * Math.abs(1 - a / (Math.PI / 5)));
};

/* Puffy cloud spanning rows 2-8, shifted down by `dy`. */
const puff = (x, y, dy = 0) => {
  const Y = y - dy;
  return Math.hypot(x - 5, Y - 6) <= 2.6 || Math.hypot(x - 9, Y - 4.8) <= 3.2 || Math.hypot(x - 12.2, Y - 6.8) <= 2.1 || (Y >= 6 && Y <= 8.8 && x >= 3 && x <= 13.5);
};
const has = (list, x, y) => list.some(([px, py]) => px === x && py === y);

/* Magnifier with a 1px plus or minus, centred on pixel (6, 6). */
const lens = (plus) =>
  grid((x, y) => {
    const d = Math.hypot(x - 6, y - 6);
    if (d >= 4.6 && d <= 6.2) return '#';
    if (x >= 10 && y >= 10 && x <= 14 && y <= 14 && Math.abs(x - y) <= 1) return '#';
    if (y === 6 && Math.abs(x - 6) <= 2) return '#';
    return plus && x === 6 && Math.abs(y - 6) <= 2 ? '#' : '.';
  });

