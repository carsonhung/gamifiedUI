#!/usr/bin/env node
/* Builds the icon set from the pixel grids in icons/*.mjs.
   Outputs src/index.css (Tailwind @utility, tree-shaken), src/all.css (plain classes, CDN),
   svg/<name>.svg and icons.json. `--check` fails when the committed outputs are stale. */
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import common from '../icons/common.mjs';
import hk from '../icons/hk.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GRID = 16;
const HALF_OPACITY = 0.5;
const HEADER = '/* Generated by gamifiedui-icons/scripts/build.mjs from icons/*.mjs. Do not edit. */\n';
const SETS = { common, hk };
const isCheck = process.argv.includes('--check');

function expand(icon, byName) {
  if (icon.from) {
    const base = byName.get(icon.from);
    if (!base) throw new Error(`${icon.name}: unknown base icon "${icon.from}"`);
    return transform(expand(base, byName), icon.transform);
  }
  const rows = icon.mirror ? icon.rows.map((r) => r + [...r].reverse().join('')) : icon.rows;
  if (rows.length !== GRID) throw new Error(`${icon.name}: ${rows.length} rows, expected ${GRID}`);
  rows.forEach((row, y) => {
    if (row.length !== GRID) throw new Error(`${icon.name}: row ${y} has ${row.length} columns`);
    if (/[^.#+]/.test(row)) throw new Error(`${icon.name}: row ${y} has characters other than . # +`);
  });
  return rows;
}

function transform(rows, kind) {
  const at = (x, y) => rows[y][x];
  const build = (fn) => Array.from({ length: GRID }, (_, y) => Array.from({ length: GRID }, (_, x) => fn(x, y)).join(''));
  if (kind === 'flipX') return build((x, y) => at(GRID - 1 - x, y));
  if (kind === 'rot90') return build((x, y) => at(y, GRID - 1 - x));
  if (kind === 'rot270') return build((x, y) => at(GRID - 1 - y, x));
  throw new Error(`unknown transform "${kind}"`);
}

function pathFor(rows, char) {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < GRID; x++) {
      if (row[x] !== char) continue;
      let end = x;
      while (row[end + 1] === char) end++;
      d += `M${x} ${y}h${end - x + 1}v1H${x}z`;
      x = end;
    }
  });
  return d;
}

function toSvg(rows) {
  const solid = pathFor(rows, '#');
  const half = pathFor(rows, '+');
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID} ${GRID}" shape-rendering="crispEdges" fill="currentColor">` +
    (solid ? `<path d="${solid}"/>` : '') +
    (half ? `<path fill-opacity="${HALF_OPACITY}" d="${half}"/>` : '') +
    '</svg>'
  );
}

function toDataUri(svg) {
  const masked = svg.replace(' fill="currentColor"', '').replaceAll('"', "'");
  return `data:image/svg+xml,${masked.replaceAll('<', '%3C').replaceAll('>', '%3E')}`;
}

function declarations(uri) {
  return `  mask: url("${uri}") center / contain no-repeat;\n  background-color: currentColor;\n`;
}

const icons = [];
for (const [set, list] of Object.entries(SETS)) {
  const byName = new Map(list.map((icon) => [icon.name, icon]));
  for (const icon of list) {
    if (icons.some((i) => i.name === icon.name)) throw new Error(`duplicate icon "${icon.name}"`);
    const svg = toSvg(expand(icon, byName));
    icons.push({ name: icon.name, set, en: icon.en, hant: icon.hant, hans: icon.hans, svg });
  }
}

const outputs = new Map();
outputs.set(
  'src/index.css',
  HEADER + icons.map((i) => `@utility gx-i-${i.name} {\n${declarations(toDataUri(i.svg))}}\n`).join('\n'),
);
outputs.set(
  'src/all.css',
  HEADER + icons.map((i) => `.gx-i-${i.name} {\n${declarations(toDataUri(i.svg))}}\n`).join('\n'),
);
outputs.set(
  'icons.json',
  `${JSON.stringify(icons.map(({ svg, ...meta }) => meta), null, 2)}\n`,
);
for (const icon of icons) outputs.set(`svg/${icon.name}.svg`, `${icon.svg}\n`);

if (isCheck) {
  const stale = [];
  for (const [file, content] of outputs) {
    const current = await readFile(path.join(ROOT, file), 'utf8').catch(() => null);
    if (current !== content) stale.push(file);
  }
  const svgs = await readdir(path.join(ROOT, 'svg')).catch(() => []);
  for (const file of svgs) if (!outputs.has(`svg/${file}`)) stale.push(`svg/${file} (orphan)`);
  if (stale.length) {
    console.error(`[icons] outputs are stale, run "npm run icons":\n- ${stale.join('\n- ')}`);
    process.exit(1);
  }
  console.log(`[icons] ok (${icons.length} icons)`);
} else {
  await rm(path.join(ROOT, 'svg'), { recursive: true, force: true });
  await mkdir(path.join(ROOT, 'svg'), { recursive: true });
  await mkdir(path.join(ROOT, 'src'), { recursive: true });
  for (const [file, content] of outputs) await writeFile(path.join(ROOT, file), content);
  console.log(`[icons] built ${icons.length} icons`);
}
