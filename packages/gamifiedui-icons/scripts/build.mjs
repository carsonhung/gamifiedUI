#!/usr/bin/env node
/* Builds the icon set from the pixel grids in icons/*.mjs.
   Outputs src/index.css (Tailwind @utility, tree-shaken), src/all.css (plain classes, CDN),
   svg/<name>.svg (animated: svg/ia-<name>.svg frame strips) and icons.json.
   `--check` fails when the committed outputs are stale. */
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import animated from '../icons/animated.mjs';
import categories from '../icons/categories.mjs';
import common from '../icons/common.mjs';
import emoji from '../icons/emoji.mjs';
import hk from '../icons/hk.mjs';
import { DEFAULTS, FALLBACK, PRESETS } from '../icons/motion.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GRID = 16;
const HALF_OPACITY = 0.5;
const HEADER = '/* Generated by gamifiedui-icons/scripts/build.mjs from icons/*.mjs. Do not edit. */\n';
const SETS = { common, emoji, hk };
const isCheck = process.argv.includes('--check');

function expand(icon, byName) {
  if (icon.from) {
    const base = byName.get(icon.from);
    if (!base) throw new Error(`${icon.name}: unknown base icon "${icon.from}"`);
    return transform(expand(base, byName), icon.transform);
  }
  const rows = icon.mirror ? icon.rows.map((r) => r + [...r].reverse().join('')) : icon.rows;
  return validate(rows, icon.name);
}

function validate(rows, label) {
  if (rows.length !== GRID) throw new Error(`${label}: ${rows.length} rows, expected ${GRID}`);
  rows.forEach((row, y) => {
    if (row.length !== GRID) throw new Error(`${label}: row ${y} has ${row.length} columns`);
    if (/[^.#+]/.test(row)) throw new Error(`${label}: row ${y} has characters other than . # +`);
  });
  return rows;
}

function transform(rows, kind) {
  const at = (x, y) => rows[y][x];
  const build = (fn) => Array.from({ length: GRID }, (_, y) => Array.from({ length: GRID }, (_, x) => fn(x, y)).join(''));
  if (kind === 'flipX') return build((x, y) => at(GRID - 1 - x, y));
  if (kind === 'rot90') return build((x, y) => at(y, GRID - 1 - x));
  if (kind === 'rot270') return build((x, y) => at(GRID - 1 - y, x));
  if (kind === 'rot180') return build((x, y) => at(GRID - 1 - x, GRID - 1 - y));
  if (kind === 'flipY') return build((x, y) => at(x, GRID - 1 - y));
  throw new Error(`unknown transform "${kind}"`);
}

function pathFor(rows, char, offsetX = 0) {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < GRID; x++) {
      if (row[x] !== char) continue;
      let end = x;
      while (row[end + 1] === char) end++;
      d += `M${x + offsetX} ${y}h${end - x + 1}v1H${x + offsetX}z`;
      x = end;
    }
  });
  return d;
}

/* One frame, or a horizontal strip of frames for animated icons. */
function toSvg(frames) {
  const solid = frames.map((rows, i) => pathFor(rows, '#', i * GRID)).join('');
  const half = frames.map((rows, i) => pathFor(rows, '+', i * GRID)).join('');
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID * frames.length} ${GRID}" shape-rendering="crispEdges" fill="currentColor">` +
    (solid ? `<path d="${solid}"/>` : '') +
    (half ? `<path fill-opacity="${HALF_OPACITY}" d="${half}"/>` : '') +
    '</svg>'
  );
}

function toDataUri(svg) {
  const masked = svg.replace(' fill="currentColor"', '').replaceAll('"', "'");
  return `data:image/svg+xml,${masked.replaceAll('<', '%3C').replaceAll('>', '%3E')}`;
}

function declarations(uri) {
  return `  mask: url("${uri}") center / contain no-repeat;\n  background-color: currentColor;\n`;
}

/* Longhands only, so gx-icon-paused / gx-icon-hover-play can set animation-play-state.
   The element must be 1em wide (gx-icon sets font-size to its size). */
function animatedDeclarations(icon) {
  return (
    `  mask: url("${toDataUri(icon.svg)}") 0 0 / ${icon.frames * 100}% 100% no-repeat;\n` +
    '  background-color: currentColor;\n' +
    `  animation-name: gx-ia-${icon.name};\n` +
    `  animation-duration: ${Math.round((icon.frames * 1000) / icon.fps)}ms;\n` +
    `  animation-timing-function: steps(${icon.frames}, end);\n` +
    '  animation-iteration-count: infinite;\n'
  );
}

const keyframes = (icon) => `@keyframes gx-ia-${icon.name} {\n  to {\n    mask-position: -${icon.frames}em 0;\n  }\n}\n`;

function presetDeclarations(name) {
  const preset = PRESETS[name];
  return (
    `  animation-name: gx-im-${name};\n` +
    `  animation-duration: ${preset.ms}ms;\n` +
    '  animation-timing-function: steps(1, end);\n' +
    '  animation-iteration-count: infinite;\n' +
    (preset.origin ? `  transform-origin: ${preset.origin};\n` : '')
  );
}

const presetKeyframes = (name) =>
  `@keyframes gx-im-${name} {\n` +
  PRESETS[name].frames.map(([pct, decl]) => `  ${pct}% {\n    ${decl};\n  }\n`).join('') +
  '}\n';

const REDUCED_UTILITY =
  '\n  @media (prefers-reduced-motion: reduce) {\n    animation: none;\n  }\n\n  [data-gx-motion="reduce"] & {\n    animation: none;\n  }\n';
const MOVING = ':is([class*="gx-ia-"], [class*="gx-im-"])';
const REDUCED_PLAIN =
  `@media (prefers-reduced-motion: reduce) {\n  ${MOVING} {\n    animation: none;\n  }\n}\n\n` +
  `[data-gx-motion="reduce"] ${MOVING} {\n  animation: none;\n}\n`;

const icons = [];
for (const [set, list] of Object.entries(SETS)) {
  const byName = new Map(list.map((icon) => [icon.name, icon]));
  for (const icon of list) {
    if (icons.some((i) => i.name === icon.name)) throw new Error(`duplicate icon "${icon.name}"`);
    const svg = toSvg([expand(icon, byName)]);
    icons.push({ name: icon.name, set, en: icon.en, hant: icon.hant, hans: icon.hans, svg });
  }
}

const moving = animated.map((icon) => {
  if (!icon.frames?.length || !icon.fps) throw new Error(`${icon.name}: animated icons need frames and fps`);
  const frames = icon.frames.map((rows, i) => validate(rows, `${icon.name} frame ${i}`));
  return { name: icon.name, set: 'animated', en: icon.en, hant: icon.hant, hans: icon.hans, fps: icon.fps, frames: frames.length, svg: toSvg(frames) };
});
if (new Set(moving.map((i) => i.name)).size !== moving.length) throw new Error('duplicate animated icon name');

for (const [name, preset] of Object.entries(DEFAULTS)) {
  if (!icons.some((i) => i.name === name)) throw new Error(`motion default for unknown icon "${name}"`);
  if (!PRESETS[preset]) throw new Error(`${name}: unknown motion preset "${preset}"`);
}
const framed = new Set(moving.map((i) => i.name));
const presetIcons = icons.filter((i) => !framed.has(i.name)).map((i) => ({ ...i, motion: DEFAULTS[i.name] ?? FALLBACK }));
const presetNames = Object.keys(PRESETS);
const animatedCount = icons.length + moving.filter((m) => !icons.some((s) => s.name === m.name)).length;

const outputs = new Map();
outputs.set(
  'src/index.css',
  HEADER +
    icons.map((i) => `@utility gx-i-${i.name} {\n${declarations(toDataUri(i.svg))}}\n`).join('\n') +
    '\n' +
    presetNames.map((p) => `@utility gx-im-${p} {\n${presetDeclarations(p)}${REDUCED_UTILITY}}\n\n${presetKeyframes(p)}`).join('\n') +
    '\n' +
    presetIcons
      .map((i) => `@utility gx-ia-${i.name} {\n${declarations(toDataUri(i.svg))}${presetDeclarations(i.motion)}${REDUCED_UTILITY}}\n`)
      .join('\n') +
    '\n' +
    moving.map((i) => `@utility gx-ia-${i.name} {\n${animatedDeclarations(i)}${REDUCED_UTILITY}}\n\n${keyframes(i)}`).join('\n'),
);
outputs.set(
  'src/all.css',
  HEADER +
    icons
      .map((i) => {
        const selectors = framed.has(i.name) ? `.gx-i-${i.name}` : `.gx-i-${i.name},\n.gx-ia-${i.name}`;
        return `${selectors} {\n${declarations(toDataUri(i.svg))}}\n`;
      })
      .join('\n') +
    '\n' +
    presetNames
      .map((p) => {
        const selectors = [`.gx-im-${p}`, ...presetIcons.filter((i) => i.motion === p).map((i) => `.gx-ia-${i.name}`)];
        return `${selectors.join(',\n')} {\n${presetDeclarations(p)}}\n\n${presetKeyframes(p)}`;
      })
      .join('\n') +
    '\n' +
    moving.map((i) => `.gx-ia-${i.name} {\n${animatedDeclarations(i)}}\n\n${keyframes(i)}`).join('\n') +
    '\n' +
    REDUCED_PLAIN,
);
const SET_CATEGORY = { emoji: 'emoji', hk: 'hong-kong' };
const categoryOf = new Map();
for (const category of categories) {
  for (const name of category.icons) {
    if (categoryOf.has(name)) throw new Error(`"${name}" is in both ${categoryOf.get(name)} and ${category.id}`);
    categoryOf.set(name, category.id);
  }
}
const allNames = new Set([...icons, ...moving].map((i) => i.name));
for (const name of categoryOf.keys()) if (!allNames.has(name)) throw new Error(`category lists unknown icon "${name}"`);
const categorise = (icon) => {
  const id = categoryOf.get(icon.name) ?? SET_CATEGORY[icon.set];
  if (!id) throw new Error(`"${icon.name}" has no category: add it to icons/categories.mjs`);
  return id;
};

outputs.set(
  'icons.json',
  `${JSON.stringify(
    [
      ...icons.map(({ svg, ...meta }) => ({
        ...meta,
        category: categorise(meta),
        motion: framed.has(meta.name) ? 'frames' : DEFAULTS[meta.name] ?? FALLBACK,
      })),
      ...moving
        .filter((i) => !icons.some((s) => s.name === i.name))
        .map(({ svg, ...meta }) => ({ ...meta, category: categorise(meta), motion: 'frames' })),
    ],
    null,
    2,
  )}\n`,
);
outputs.set(
  'categories.json',
  `${JSON.stringify(categories.map(({ icons: _, ...meta }) => meta), null, 2)}\n`,
);
for (const icon of icons) outputs.set(`svg/${icon.name}.svg`, `${icon.svg}\n`);
for (const icon of moving) outputs.set(`svg/ia-${icon.name}.svg`, `${icon.svg}\n`);

if (isCheck) {
  const stale = [];
  for (const [file, content] of outputs) {
    const current = await readFile(path.join(ROOT, file), 'utf8').catch(() => null);
    if (current !== content) stale.push(file);
  }
  const svgs = await readdir(path.join(ROOT, 'svg')).catch(() => []);
  for (const file of svgs) if (!outputs.has(`svg/${file}`)) stale.push(`svg/${file} (orphan)`);
  if (stale.length) {
    console.error(`[icons] outputs are stale, run "npm run icons":\n- ${stale.join('\n- ')}`);
    process.exit(1);
  }
  console.log(`[icons] ok (${icons.length} icons, ${animatedCount} animated, ${presetNames.length} motions)`);
} else {
  await rm(path.join(ROOT, 'svg'), { recursive: true, force: true });
  await mkdir(path.join(ROOT, 'svg'), { recursive: true });
  await mkdir(path.join(ROOT, 'src'), { recursive: true });
  for (const [file, content] of outputs) await writeFile(path.join(ROOT, file), content);
  console.log(`[icons] built ${icons.length} icons, ${animatedCount} animated, ${presetNames.length} motions`);
}
